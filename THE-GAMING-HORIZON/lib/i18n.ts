export function convertFromUsd(usdAmount: number, currency: CurrencyOption): number {
  return usdAmount * currency.rate
}

export function formatCurrency(usdAmount: number, currency: CurrencyOption, languageTag: string): string {
  const amount = convertFromUsd(usdAmount, currency)
  try {
    return new Intl.NumberFormat(languageTag, {
      style: 'currency',
      currency: currency.code,
      minimumFractionDigits: currency.code === 'JPY' ? 0 : 2,
      maximumFractionDigits: currency.code === 'JPY' ? 0 : 2,
    }).format(amount)
  } catch {
    return `${currency.symbol}${amount.toFixed(currency.code === 'JPY' ? 0 : 2)}`
  }
}
