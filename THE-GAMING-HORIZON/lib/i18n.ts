// Site-wide language + currency data.
//
// This is intentionally a plain dictionary rather than a heavyweight i18n
// library — the project has no translation pipeline/backend, so strings are
// maintained by hand here, the same way lib/pricing.ts hand-maintains plan
// copy. LocaleProvider (components/providers/locale-provider.tsx) is the
// only thing that should read this file's shape directly; everywhere else
// should go through useLocale().t(key).

